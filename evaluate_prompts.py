"""Compare the OLD review prompt with the NEW prompts on public repositories.

Run from the project root (needs Ollama running and internet access):

    python evaluate_prompts.py
    python evaluate_prompts.py https://github.com/pallets/click --model llama3.2:3b

For every repository it writes prompt_examples/<repo>.md containing the old
output and the new outputs side by side. These files are your "poor versus
improved" evidence for the README and the demo.
"""
import argparse
import re
from pathlib import Path

from openai import OpenAI

from analyzer.ai_review import generate_repository_review_v1  # the OLD single prompt
from analyzer.github_utils import get_repository_files, get_repository_info
from analyzer.repository_analyzer import analyze_repository
from commit.prompts import (
    MAX_OUTPUT_TOKENS,
    PROMPT_BUILDERS,
    PROMPT_VERSION,
    readme_improvements_markdown,
    count_unverified_findings,
    flag_unverified_findings,
    readme_checklist_markdown,
)

DEFAULT_REPOS = [
    "https://github.com/pallets/click",
    "https://github.com/psf/requests",
    "https://github.com/Textualize/rich",
]

client = OpenAI(base_url="http://localhost:11434/v1", api_key="ollama")


def ask(messages: list[dict], model: str, max_tokens: int = 400) -> str:
    response = client.chat.completions.create(
        model=model, messages=messages, temperature=0.2, max_tokens=max_tokens
    )
    return response.choices[0].message.content or "(empty response)"


def evaluate(url: str, model: str, out_dir: Path) -> None:
    print(f"\n=== {url}")
    info = get_repository_info(url)
    report = {**analyze_repository(get_repository_files(url)), "name": info["name"]}

    lines = [
        f"# Prompt comparison: {info['name']}",
        f"Model: `{model}` | New prompt version: {PROMPT_VERSION}",
        f"Files analysed: {report['total_files']}",
        "",
        "## OLD: single combined prompt",
        generate_repository_review_v1(report),
        "",
    ]

    for name, builder in PROMPT_BUILDERS.items():
        print(f"  running {name} ...")
        if name == "documentation":  # generated by code, no model call needed
            text = readme_checklist_markdown(report) + "\n\n" + readme_improvements_markdown(report)
        else:
            text = ask(builder(report), model, MAX_OUTPUT_TOKENS[name])
        if name == "code_review":
            text = flag_unverified_findings(text, report)
            lines.append(f"<!-- unverified findings: {count_unverified_findings(text)} -->")
        lines += [f"## NEW: {name}", text, ""]

    lines += [
        "## Manual scoring (fill in)",
        "- Invented files / functions (old): ",
        "- Invented files / functions (new): ",
        "- Findings with real evidence (old / new): ",
        "- Which is more useful, and why: ",
    ]

    out_dir.mkdir(exist_ok=True)
    slug = re.sub(r"[^a-zA-Z0-9_-]+", "-", info["name"]).strip("-")
    path = out_dir / f"{slug}.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  saved {path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("repos", nargs="*", default=DEFAULT_REPOS)
    parser.add_argument("--model", default="llama3.2:3b")
    args = parser.parse_args()

    for repo_url in args.repos:
        try:
            evaluate(repo_url, args.model, Path("prompt_examples"))
        except Exception as error:  # keep going if one repo fails
            print(f"  FAILED: {error}")